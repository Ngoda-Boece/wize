import { z } from "zod";
import {
  EXPERIENCE_LEVELS,
  INTERACTION_PREFERENCES,
  LEARNING_GOALS,
  MODES,
  OBJECTIVE_KINDS,
  OBJECTIVE_STATUSES,
} from "./types";

export const LIMITS = {
  messageMaxChars: 8_000,
  subjectMaxChars: 500,
  titleMaxChars: 160,
  displayNameMaxChars: 80,
  interestMaxChars: 40,
  interestsMax: 8,
  objectiveDescriptionMaxChars: 1_000,
} as const;

export const modeSchema = z.enum(MODES);

const trimmed = (max: number) => z.string().trim().min(1).max(max);

export const chatRequestSchema = z
  .object({
    conversationId: z.uuid(),
    // Present for a new user message; absent when retrying the reply to the
    // last stored user message.
    message: trimmed(LIMITS.messageMaxChars).optional(),
    // Idempotency key generated by the client for each submission, so a double
    // click or a network retry never stores the same message twice.
    clientMessageId: z
      .string()
      .regex(/^[A-Za-z0-9_-]{1,64}$/)
      .optional(),
    retry: z.boolean().optional(),
  })
  .refine((v) => (v.retry ? !v.message : !!v.message && !!v.clientMessageId), {
    message: "Requête de chat invalide",
  });
export type ChatRequest = z.infer<typeof chatRequestSchema>;

export const newConversationSchema = z.object({
  subject: trimmed(LIMITS.subjectMaxChars),
  mode: modeSchema,
  objectiveId: z.uuid().nullable().optional(),
});

export const conversationPatchSchema = z
  .object({
    title: trimmed(LIMITS.titleMaxChars).optional(),
    mode: modeSchema.optional(),
  })
  .refine((v) => v.title !== undefined || v.mode !== undefined, { message: "Rien à modifier" });

export const profileSchema = z.object({
  displayName: z.string().trim().max(LIMITS.displayNameMaxChars).nullable(),
  learningInterests: z.array(trimmed(LIMITS.interestMaxChars)).max(LIMITS.interestsMax),
  experienceLevel: z.enum(EXPERIENCE_LEVELS).nullable(),
  learningGoal: z.enum(LEARNING_GOALS).nullable(),
  interactionPreference: z.enum(INTERACTION_PREFERENCES).nullable(),
  personalizationEnabled: z.boolean(),
});
export type ProfileInput = z.infer<typeof profileSchema>;

export const objectiveCreateSchema = z.object({
  title: trimmed(LIMITS.titleMaxChars),
  description: z.string().trim().max(LIMITS.objectiveDescriptionMaxChars).default(""),
  kind: z.enum(OBJECTIVE_KINDS),
});

export const objectiveStatusSchema = z.enum(OBJECTIVE_STATUSES);

export const credentialsSchema = z.object({
  email: z.email({ message: "Adresse e-mail invalide." }),
  password: z.string().min(8, { message: "Le mot de passe doit contenir au moins 8 caractères." }).max(128),
});
